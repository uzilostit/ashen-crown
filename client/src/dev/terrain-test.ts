import * as THREE from "three";
import { PaperKit } from "../render/paper";
import { buildTerrain } from "../render/terrain";
const r = new THREE.WebGLRenderer({ antialias: true });
r.setSize(innerWidth, innerHeight);
r.shadowMap.enabled = true;
r.shadowMap.type = THREE.PCFSoftShadowMap;
r.toneMapping = THREE.ACESFilmicToneMapping;
document.body.append(r.domElement);
const scene = new THREE.Scene();
scene.background = new THREE.Color("#c9b99a");
scene.fog = new THREE.FogExp2("#c9b99a", 0.004);
const cam = new THREE.PerspectiveCamera(32, innerWidth / innerHeight, 1, 800);
const q=new URLSearchParams(location.search); if(q.get('close')){cam.position.set(60, 28, 70); cam.lookAt(55, 0, 20);} else {cam.position.set(0, 150, 180); cam.lookAt(0, 0, 10);}
scene.add(new THREE.HemisphereLight("#fff1d6", "#4a4030", 1.4));
const sun = new THREE.DirectionalLight("#ffe2b0", 3);
sun.position.set(-90, 120, 60); sun.castShadow = true;
sun.shadow.mapSize.set(2048, 2048);
Object.assign(sun.shadow.camera, { left: -130, right: 130, top: 130, bottom: -130, near: 10, far: 400 });
scene.add(sun);
const t0 = performance.now();
const kit = new PaperKit(512);
const terrain = buildTerrain(kit, 1.6);
scene.add(terrain.group);
(window as any).__ms = performance.now() - t0;
let tris = 0; terrain.group.traverse((o: any) => { if (o.isMesh) tris += o.geometry.attributes.position.count / 3; });
(window as any).__tris = tris;
terrain.update(0, 0);
r.render(scene, cam);
(window as any).__done = true;
